  function locale() {
    const language = globalThis.chrome?.i18n?.getUILanguage?.()
      || globalThis.document?.documentElement?.dataset?.clatriLocale
      || globalThis.navigator?.language || "en";
    return /^es(?:[-_]|$)/i.test(language) ? "es" : "en";
  }
  function t(message, values = {}) {
    const text = locale() === "es" && Object.hasOwn(spanish, message) ? spanish[message] : message;
    return String(text).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  }
  globalThis.ClatriI18n = Object.freeze({ t, locale });
